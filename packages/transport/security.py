def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def signature(scope, timestamp, body):
    return hmac.new(
        bytes.fromhex(token("webhook", scope)), str(timestamp).encode() + b"." + body, hashlib.sha256
    ).hexdigest()


def verify_signature(scope, timestamp, body, supplied, now=None):
    try:
        stamp = int(timestamp)
    except (TypeError, ValueError):
        raise HTTPException(401, "Webhook 时间无效") from None
    if abs((time.time() if now is None else now) - stamp) > 300:
        raise HTTPException(401, "Webhook 超出五分钟时间窗口")
    if not hmac.compare_digest(signature(scope, stamp, body), supplied or ""):
        raise HTTPException(401, "Webhook 签名无效")


def redact(value, secret_values=()):
    sensitive = (
        "authorization",
        "cookie",
        "secret",
        "token",
        "password",
        "signature",
        "api_key",
        "customer",
        "recipient",
        "payee",
    )
    if isinstance(value, dict):
        return {
            redact_text(k, secret_values): (
                "sha256:" + digest(v)
                if k.lower() in {"recipient", "payee"}
                else "[REDACTED]"
                if any(s in k.lower() for s in sensitive)
                else redact(v, secret_values)
            )
            for k, v in value.items()
        }
    if isinstance(value, list):
        return [redact(v, secret_values) for v in value]
    if isinstance(value, str):
        return redact_text(value, secret_values)
    return value


def redact_text(value, secret_values=()):
    """Remove supplied credentials and recognizable local tokens from shared free text."""
    for secret in secret_values:
        if secret:
            value = value.replace(secret, "[REDACTED]")
    return re.sub(r"(?<![A-Za-z0-9_-])sim_[A-Za-z0-9_-]{43}(?![A-Za-z0-9_-])", "[REDACTED]", value)
