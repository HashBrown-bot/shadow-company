import json
import os
import re
import secrets
import time
from pathlib import Path
from uuid import UUID

from fastapi import HTTPException, Request

from packages.contracts.config import Model

ROLES = (
    "support",
    "approver",
    "customer_a",
    "customer_b",
    "put_admin",
    "provider_execute",
    "provider_reader",
    "provider_admin",
    "webhook",
)


class Scope(Model):
    project_id: UUID
    run_id: UUID

    @property
    def params(self):
        return {"p": self.project_id, "r": self.run_id}

    @property
    def namespace(self):
        return f"{self.project_id}/{self.run_id}"


def provision(path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    if not path.exists():
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            json.dump({role: secrets.token_hex(32) for role in ROLES}, f)
    if path.stat().st_mode & 0o077:
        raise RuntimeError("示例凭据文件权限必须为 0600")
    # Extend only our generated example identity bundle; preserve existing keys.
    generated = json.loads(path.read_text())
    if any(role not in generated for role in ROLES):
        generated.update({role: secrets.token_hex(32) for role in ROLES if role not in generated})
        path.write_text(json.dumps(generated))


def service_credentials(path, service):
    """Give each sample process only its needed generated test keys."""
    roles = {
        "refund-put": (
            "support",
            "approver",
            "customer_a",
            "customer_b",
            "put_admin",
            "provider_execute",
            "webhook",
        ),
        "payment-provider": ("provider_execute", "provider_reader", "provider_admin", "webhook"),
        "platform": (
            "support",
            "approver",
            "customer_a",
            "customer_b",
            "put_admin",
            "provider_reader",
            "provider_admin",
            "webhook",
        ),
    }[service]
    path = Path(path)
    provision(path)
    generated = json.loads(path.read_text())
    target = path.with_name(path.stem + "-" + service + ".json")
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, "w") as stream:
        json.dump({role: generated[role] for role in roles}, stream)
    return target


def key(role):
    # This file is generated by our launcher, never imported from a user's real credentials.
    path = Path(os.environ.get("EXAMPLE_CREDENTIAL_FILE", ".local/example-credentials.json"))
    if path.stat().st_mode & 0o077:
        raise RuntimeError("示例凭据文件权限必须为 0600")
    return bytes.fromhex(json.loads(path.read_text())[role])


def token(role, scope):
    return hmac.new(key(role), scope.namespace.encode(), hashlib.sha256).hexdigest()


def headers(role, scope):
    return {
        "Authorization": "Bearer " + token(role, scope),
        "X-Project-ID": str(scope.project_id),
        "X-Run-ID": str(scope.run_id),
        "X-Run-Namespace": scope.namespace,
    }


def authorize(request: Request, *roles):
    try:
        scope = Scope(project_id=request.headers["X-Project-ID"], run_id=request.headers["X-Run-ID"])
        if request.headers.get("X-Run-Namespace") != scope.namespace:
            raise ValueError()
        provided = request.headers.get("Authorization", "").removeprefix("Bearer ")
        for role in roles:
            if hmac.compare_digest(provided, token(role, scope)):
                return scope, role
    except (KeyError, ValueError):
        pass
    raise HTTPException(403, "测试身份或命名空间无效")


